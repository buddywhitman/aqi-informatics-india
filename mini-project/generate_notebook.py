add_md("## 3. Rolling Baselines & Data Leakage Prevention\nA 6-hour backward-looking rolling window is applied. Crucially, `.shift(1)` is enforced prior to `.rolling(6)` to strictly decouple the evaluated hour from its own baseline.")
add_code("""# Rolling median and rolling MAD with .shift(1)
df['calc_roll_med'] = df['pollution_index'].shift(1).rolling(6, min_periods=3).median()
df['calc_roll_mad'] = df['pollution_index'].shift(1).rolling(6, min_periods=3).apply(
    lambda x: np.median(np.abs(x - np.median(x))), raw=True
)

# Relative jump metric
delta = (df['pollution_index'] - df['calc_roll_med']).abs()
df['calc_rel_jump'] = delta / (df['calc_roll_med'] + 1)

print("Max relative jump observed on rescaled index:", round(df['calc_rel_jump'].max(), 3))
print("Quantiles of relative jump:")
print(df['calc_rel_jump'].quantile([0.5, 0.75, 0.9, 0.95, 0.99, 1.0]).round(3))""")

