add_md("## 7. Interactive Threshold Sandbox: Proving Affine Compression\nThis interactive sandbox demonstrates the mathematical diagnostic: why relative percentage thresholds on affine-transformed scales compress growth rates, and what happens when thresholds are recalibrated.")
add_code("""def run_threshold_experiment(jump_threshold=1.0, extreme_pct=0.95):
    test_df = df.copy()
    q_val = test_df['pollution_index'].quantile(extreme_pct)
    
    ext_flag = (test_df['pollution_index'] > q_val).astype(int)
    jump_flag = (test_df['relative_jump'] > jump_threshold).astype(int)
    low_wind = (test_df['wind_speed'] < 0.6 * test_df['wind_speed'].median()).astype(int)
    unsupp = (jump_flag & (1 - low_wind)).astype(int)
    disag = ((test_df['pm25_severity'] - test_df['no2_severity']).abs() > 2.0).astype(int)
    
    score = 35 * ext_flag + 35 * jump_flag + 20 * unsupp + 10 * disag
    status = pd.cut(score, bins=[-1, 30, 65, np.inf], labels=['Normal', 'Watch', 'Suspicious'])
    
    counts = status.value_counts()
    print(f"--- Experiment: Jump Threshold = {jump_threshold}, Extreme Percentile = {int(extreme_pct*100)}th ---")
    print(counts.to_string())
    return counts

# Standard Project Rule (Threshold = 1.0) -> Suspicious = 0
run_threshold_experiment(jump_threshold=1.0, extreme_pct=0.95)

# Recalibrated Threshold (Threshold = 0.35) -> Shows active Suspicious classifications
run_threshold_experiment(jump_threshold=0.35, extreme_pct=0.95)""")

