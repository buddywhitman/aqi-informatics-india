"""
make_tables_numbers.py -- single source of truth for every number quoted in the manuscript.

Reads only committed CSV/JSON artifacts under reports/ and writes
  paper/generated/numbers.tex     \\newcommand macros used in the text (one macro per quoted number)
  paper/generated/claims.csv      ledger: macro, value, source file, how it was computed
  paper/generated/tab_*.tex       every results table in the paper
verify_submission.py re-runs this script into a temporary directory and fails if any output differs, so the
PDF cannot drift from the artifacts.

    python src/synthesis/make_tables_numbers.py [--out DIR]
"""
