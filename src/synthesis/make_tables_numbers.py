class Ledger:
    def __init__(self):
        self.rows = []

    def add(self, name, value, src, how, fmt='{:.3f}'):
        txt = fmt.format(value) if not isinstance(value, str) else value
        self.rows.append(dict(macro=name, value=txt, source=src, how=how))
        return txt

    def tex(self):
        out = ['% AUTO-GENERATED by src/synthesis/make_tables_numbers.py -- do not edit by hand']
        for r in self.rows:
            out.append('\\newcommand{\\%s}{%s}' % (r['macro'], r['value']))
        return '\n'.join(out) + '\n'


def pct(x, d=0):
    return ('{:.%df}' % d).format(100 * x)


def f(x, d=2):
    return ('{:.%df}' % d).format(x)


