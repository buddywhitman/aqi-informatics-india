"""
make_rebuttal_tables.py -- generates paper/generated/rebuttal_numbers.tex and the tables of the identification /
deconvolution section from the committed CSVs in reports/ and reports/rebuttal/.  Same discipline as
src/synthesis/make_tables_numbers.py: no number in the manuscript is typed by hand.

    python src/rebuttal/make_rebuttal_tables.py [--out DIR]
"""
import argparse, os
import numpy as np, pandas as pd
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
R = lambda *p: os.path.join(ROOT, 'reports', *p)
ap = argparse.ArgumentParser(); ap.add_argument('--out', default=os.path.join(ROOT, 'paper', 'generated')); a = ap.parse_args()
os.makedirs(a.out, exist_ok=True)
M = []                                                         # (macro, value string)
def mac(name, val): M.append((name, val))
f2 = lambda x: f'{x:.2f}'; f3 = lambda x: f'{x:.3f}'; pc = lambda x: f'{100 * x:.0f}'

fr = pd.read_csv(R('synthesis', 'frontier_designs_summary.csv')); fr = fr[fr.p00 == 0.88]
dcf = pd.read_csv(R('rebuttal', 'deconv_summary.csv')); jf = pd.read_csv(R('rebuttal', 'joint_frontier_summary.csv')).set_index('dz')
ss = pd.read_csv(R('synthesis', 'semisynthetic_hourly_summary.csv'))
dcs = pd.read_csv(R('rebuttal', 'deconv_semisynthetic_summary.csv')); js = pd.read_csv(R('rebuttal', 'joint_semisynthetic_summary.csv'))
orf = lambda dz, c: fr[(fr.dz == dz) & (fr.method == 'OR-DML')].iloc[0][c]
dcr = lambda dz, c: dcf[(dcf.dz == dz) & (dcf.method.str.startswith('DC-DML'))].iloc[0][c]
orc = lambda city: ss[(ss.city == city) & (ss.method == 'OR-DML (posterior-adjusted)')].iloc[0]
dcc = lambda city: dcs[(dcs.city == city) & (dcs.method == 'DC-DML (X basis)')].iloc[0]
jsc = lambda city: js[(js.city == city) & (js.method == 'Joint MLE, regime-specific theta')].iloc[0]
cj = lambda city: js[(js.city == city) & (js.method == 'Joint MLE, common theta')].iloc[0]
cities = ['Delhi', 'Mumbai', 'Bengaluru', 'Kolkata']
for dz, tag in ((0.5, 'Half'), (1.0, 'One'), (2.0, 'Two'), (4.0, 'Four')):
    mac(f'RbOR{tag}', f3(orf(dz, 'mean_abs_bias'))); mac(f'RbORCov{tag}', pc(orf(dz, 'coverage')))
    mac(f'RbDC{tag}', f3(dcr(dz, 'mean_abs_bias'))); mac(f'RbDCCov{tag}', pc(dcr(dz, 'coverage')))
    mac(f'RbDCRmse{tag}', f2(dcr(dz, 'rmse'))); mac(f'RbORRmse{tag}', f2(fr[(fr.dz == dz) & (fr.method == 'OR-DML')].iloc[0]['rmse']))
    mac(f'RbDCThCov{tag}', pc(dcr(dz, 'cover_theta'))); mac(f'RbJF{tag}', f3(jf.loc[dz, 'mean_abs_bias']))
for i, c in enumerate(cities):
    mac(f'RbORCity{c}', f2(orc(c).mean_abs_bias)); mac(f'RbDCCity{c}', f2(dcc(c).mean_abs_bias))
    mac(f'RbJCity{c}', f2(jsc(c).mean_abs_bias)); mac(f'RbJCommonCity{c}', f2(cj(c).mean_abs_bias))
    mac(f'RbDCCityCov{c}', pc(dcc(c).coverage)); mac(f'RbORCityCov{c}', pc(orc(c).coverage))
mac('RbJCommonMin', f2(min(cj(c).mean_abs_bias for c in cities))); mac('RbJCommonMax', f2(max(cj(c).mean_abs_bias for c in cities)))
mac('RbDCKolkataMed', f2(pd.read_csv(R('rebuttal', 'deconv_semisynthetic_raw.csv')).query("city=='Kolkata' and method=='DC-DML (X basis)'").bias.abs().median()))
raw = pd.read_csv(R('rebuttal', 'deconv_semisynthetic_raw.csv'))
mac('RbDCZMaxKolkata', f'{raw.query("city==\'Kolkata\' and method==\'DC-DML (X + Z additive)\'").bias.abs().max():,.0f}'.replace(',', '{,}'))
t10 = pd.read_csv(R('rebuttal', 'deconv_table10_summary.csv'))
mac('RbTenJointMax', f2(t10.joint.abs().max())); mac('RbTenDCMin', f2(t10.dc.abs().min())); mac('RbTenDCMax', f2(t10.dc.abs().max()))
mac('RbTenDMLMin', f2(t10.dml.abs().min())); mac('RbTenDMLMax', f2(t10.dml.abs().max()))
ba = pd.read_csv(R('rebuttal', 'bias_aware_ci_summary.csv')).set_index('dz')
mac('RbBeff', f'{ba.beff.iloc[0]:.1f}')
for dz, tag in ((1.0, 'One'), (2.0, 'Two'), (4.0, 'Four')):
    for col, t in (('cov_0x', 'Zero'), ('cov_half', 'Half'), ('cov_1x', 'Full'), ('cov_2x', 'Double')):
        mac(f'RbBA{t}{tag}', pc(ba.loc[dz, col]))
mac('RbBAReqOne', f'{ba.loc[1.0, "median_b_required"]:.1f}')
mac('RbBALawOne', f2(ba.loc[1.0, 'mean_plugin'])); mac('RbBAMeasOne', f2(ba.loc[1.0, 'mean_bias']))
he = pd.read_csv(R('rebuttal', 'hetero_law_check.csv'))
mac('RbHetErrMin', f'{he["rel_err_hetero_%"].min():.2f}'); mac('RbHetErrMax', f'{he["rel_err_hetero_%"].max():.1f}')
mac('RbHomErrMin', f'{he["rel_err_homo_%"].min():.0f}'); mac('RbHomErrMax', f'{he["rel_err_homo_%"].max():.0f}')
lr = pd.read_csv(R('rebuttal', 'lambda_rule_check.csv'))
mac('RbLamLo', f'{lr["lambda"].min() * 1e4:.1f}'); mac('RbLamHi', f'{lr["lambda"].max() * 1e4:.1f}')
mac('RbSqrtNLam', f'{lr.sqrtN_lambda.median():.3f}'); mac('RbShrinkBound', f'{lr.shrink_bias_bound.median():.3f}')
with open(os.path.join(a.out, 'rebuttal_numbers.tex'), 'w') as fh:
    fh.write('% AUTO-GENERATED by src/rebuttal/make_rebuttal_tables.py\n')
    for k, v in M:
        fh.write(f'\\newcommand{{\\{k}}}{{{v}}}\n')

# ---- main-text table: estimators beyond the two-stage plug-in
rows = [('OR-DML (two-stage, posterior-adjusted)', 'OR'), ('DC-DML (deconvolution)', 'DC'), ('Joint MLE (regime-specific effects)', 'J')]
L = [r'% AUTO-GENERATED by src/rebuttal/make_rebuttal_tables.py', r'\begin{tabular}{lcccccccc}', r'\toprule',
     r' & \multicolumn{2}{c}{Frontier $\Delta_Z{=}1$} & \multicolumn{2}{c}{Frontier $\Delta_Z{=}2$} & \multicolumn{4}{c}{City benchmark} \\',
     r'\cmidrule(lr){2-3}\cmidrule(lr){4-5}\cmidrule(lr){6-9}',
     r'Estimator & $|$bias$|$ & cover. & $|$bias$|$ & cover. & Delhi & Mumbai & Bengaluru & Kolkata \\', r'\midrule']
def cell(kind, dz):
    if kind == 'OR': return f'{orf(dz, "mean_abs_bias"):.2f} & {pc(orf(dz, "coverage"))}\\%'
    if kind == 'DC': return f'{dcr(dz, "mean_abs_bias"):.2f} & {pc(dcr(dz, "coverage"))}\\%'
    return f'{jf.loc[dz, "mean_abs_bias"]:.2f} & --'
def city(kind, c):
    return f2({'OR': orc, 'DC': dcc, 'J': jsc}[kind](c).mean_abs_bias)
for name, kind in rows:
    L.append(f'{name} & {cell(kind, 1.0)} & {cell(kind, 2.0)} & ' + ' & '.join(city(kind, c) for c in cities) + r' \\')
L += [r'\bottomrule', r'\end{tabular}']
open(os.path.join(a.out, 'tab_beyond_twostage.tex'), 'w').write('\n'.join(L) + '\n')

# ---- appendix tables
nm = {'base': 'HMM correctly specified', 'nonlinX': 'nonlinear $f(X)$', 'K3true': 'true $K{=}3$, fitted $K{=}2$',
      'heavyZ': 'heavy-tailed ($t_3$) proxy noise', 'hetero': 'heterogeneous $\\theta(S)$'}
L = [r'% AUTO-GENERATED by src/rebuttal/make_rebuttal_tables.py', r'\begin{tabular}{lcccc}', r'\toprule',
     r'Scenario & $\Delta_T$ & Posterior-DML & Joint MLE & DC-DML \\', r'\midrule']
for _, r in t10.iterrows():
    L.append(f'{nm[r.scen]} & {int(r.dT)} & {r.dml:+.2f} ({r.rmse_dml:.2f}) & {r.joint:+.2f} ({r.rmse_joint:.2f}) & {r.dc:+.2f} ({r.rmse_dc:.2f}) \\\\')
L += [r'\bottomrule', r'\end{tabular}']
open(os.path.join(a.out, 'tab_dc_table10.tex'), 'w').write('\n'.join(L) + '\n')

L = [r'% AUTO-GENERATED by src/rebuttal/make_rebuttal_tables.py', r'\begin{tabular}{cccccc}', r'\toprule',
     r'$\Delta_Z$ & budget $0$ & $0.5\,b_{\rm eff}$ & $b_{\rm eff}$ & $2\,b_{\rm eff}$ & median required budget \\', r'\midrule']
for dz, r in ba.iterrows():
    L.append(f'{dz:g} & {pc(r.cov_0x)}\\% & {pc(r.cov_half)}\\% & {pc(r.cov_1x)}\\% & {pc(r.cov_2x)}\\% & {r.median_b_required:.1f} \\\\')
L += [r'\bottomrule', r'\end{tabular}']
open(os.path.join(a.out, 'tab_bias_aware.tex'), 'w').write('\n'.join(L) + '\n')

L = [r'% AUTO-GENERATED by src/rebuttal/make_rebuttal_tables.py', r'\begin{tabular}{ccccccc}', r'\toprule',
     r'$\sigma_0$ & $\sigma_1$ & separation & measured & law with $E[\sigma_S^2]$ & law with $\bar\sigma^2$ & $E[\sigma_S^2]$ true / plug-in \\', r'\midrule']
for _, r in he.iterrows():
    L.append(f'{r.s0:g} & {r.s1:g} & {r.sep:g} & {r.measured:.3f} & {r.law_hetero:.3f} & {r.law_homo_avg_sigma:.3f} & {r.Esig2_true:.2f} / {r.Esig2_plugin:.2f} \\\\')
L += [r'\bottomrule', r'\end{tabular}']
open(os.path.join(a.out, 'tab_hetero.tex'), 'w').write('\n'.join(L) + '\n')
print('wrote', len(M), 'macros and 4 tables to', a.out)
